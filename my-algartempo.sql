-- Helpers
create or replace function public.is_admin_user()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.admin_users where id = auth.uid()); $$;

-- Remove/recreate portal policies safely

do $$ declare r record; begin
  for r in select policyname, tablename from pg_policies where schemaname='public' and tablename in (
    'employee_profiles','employee_placements','employee_shifts','employee_hours','employee_documents',
    'employee_leave_requests','employee_requests','employee_notifications') loop
    execute format('drop policy if exists %I on public.%I', r.policyname, r.tablename);
  end loop;
end $$;


-- Bucket privado para documentos dos colaboradores
insert into storage.buckets (id, name, public) values ('employee-documents','employee-documents',false)
on conflict (id) do update set public=false;

drop policy if exists employee_docs_self_read on storage.objects;
drop policy if exists employee_docs_admin_all on storage.objects;
create policy employee_docs_self_read on storage.objects for select to authenticated
using (bucket_id='employee-documents' and ((storage.foldername(name))[1]=auth.uid()::text or public.is_admin_user()));
create policy employee_docs_admin_all on storage.objects for all to authenticated
using (bucket_id='employee-documents' and public.is_admin_user())
with check (bucket_id='employee-documents' and public.is_admin_user());

-- Trigger simples para updated_at
create or replace function public.touch_employee_updated_at() returns trigger language plpgsql as $$
begin new.updated_at=now(); return new; end; $$;

drop trigger if exists employee_profiles_touch on public.employee_profiles;
create trigger employee_profiles_touch before update on public.employee_profiles for each row execute function public.touch_employee_updated_at();
drop trigger if exists employee_leave_touch on public.employee_leave_requests;
create trigger employee_leave_touch before update on public.employee_leave_requests for each row execute function public.touch_employee_updated_at();
drop trigger if exists employee_requests_touch on public.employee_requests;
create trigger employee_requests_touch before update on public.employee_requests for each row execute function public.touch_employee_updated_at();

